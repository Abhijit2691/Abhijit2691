
import { useEffect, useState } from "react";
import API_BASE_URL from "./config/api.js";
const API_URL = `${API_BASE_URL}/api/mottainai`;

const CATEGORIES = [
  "Money",
  "Food",
  "Time",
  "Water",
  "Electricity",
  "Other",
];

// Return today's date in the computer's local timezone.
function getToday() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");

  return year + "-" + month + "-" + day;
}

function MottainaiTracker() {
  const [records, setRecords] = useState([]);
  const [category, setCategory] = useState("Money");
  const [description, setDescription] = useState("");
  const [amount, setAmount] = useState("");
  const [lesson, setLesson] = useState("");

  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [message, setMessage] = useState("");

  // Load waste records from the backend when the component mounts.
  useEffect(() => {
    let active = true;

    async function loadRecords() {
      try {
        const response = await fetch(API_URL);
        const result = await response.json();

        if (!response.ok || !result.success) {
          throw new Error(
            result.message || "Could not load waste records."
          );
        }

        if (active) {
          // Convert database field names to the names used by this UI.
          const loadedRecords = result.data.map((record) => ({
            ...record,
            date: record.record_date,
            amount:
              record.amount === null || record.amount === undefined
                ? null
                : Number(record.amount),
          }));

          setRecords(loadedRecords);
        }
      } catch (error) {
        if (active) {
          setMessage(
            error.message || "Could not connect to the Mottainai API."
          );
        }
      } finally {
        if (active) {
          setLoading(false);
        }
      }
    }

    loadRecords();

    // Prevent state updates if the component is unmounted.
    return () => {
      active = false;
    };
  }, []);

  // Save a new waste record in SQLite through the API.
  async function addRecord(event) {
    event.preventDefault();

    if (!description.trim() || !lesson.trim()) {
      setMessage("Please enter a description and a lesson.");
      return;
    }

    // Amount is optional. Save 0 when the field is left empty.
    const numericAmount = amount.trim() === "" ? 0 : Number(amount);

    if (
      !Number.isFinite(numericAmount) ||
      numericAmount < 0 ||
      numericAmount > 1000000000
    ) {
      setMessage("Enter a valid non-negative amount.");
      return;
    }

    setSaving(true);
    setMessage("");

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          category,
          description: description.trim(),
          amount: numericAmount,
          lesson: lesson.trim(),
          record_date: getToday(),
        }),
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(result.message || "Could not save the record.");
      }

      // Use the record ID generated by SQLite.
      const savedRecord = {
        ...result.data,
        date: result.data.record_date,
        amount: Number(result.data.amount || 0),
      };

      setRecords((previousRecords) => [
        savedRecord,
        ...previousRecords,
      ]);

      setDescription("");
      setAmount("");
      setLesson("");
      setMessage("Waste record saved successfully.");
    } catch (error) {
      setMessage(error.message || "Could not save the record.");
    } finally {
      setSaving(false);
    }
  }

  // Delete a record from the database.
  async function deleteRecord(id) {
    if (!window.confirm("Delete this waste record?")) {
      return;
    }

    setMessage("");

    try {
      const response = await fetch(API_URL + "/" + id, {
        method: "DELETE",
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(result.message || "Could not delete the record.");
      }

      setRecords((previousRecords) =>
        previousRecords.filter((record) => record.id !== id)
      );

      setMessage("Waste record deleted successfully.");
    } catch (error) {
      setMessage(error.message || "Could not delete the record.");
    }
  }

  // Only Money-category records contribute to money wasted.
  const moneyWasted = records
    .filter((record) => record.category === "Money")
    .reduce((total, record) => total + (record.amount ?? 0), 0);

  // Count records in each category.
  const categoryCounts = records.reduce((counts, record) => {
    counts[record.category] = (counts[record.category] || 0) + 1;
    return counts;
  }, {});

  return (
    <section className="tracker-card mottainai-tracker">
      <p className="principle-label">JAPANESE PRINCIPLE</p>

      <h2>♻️ Mottainai — Reduce Waste</h2>

      <p>
        Notice what you waste, learn from it, and make a small change.
      </p>

      <div className="mottainai-summary">
        <div>
          <strong>{records.length}</strong>
          <span>Waste records</span>
        </div>

        <div>
          <strong>
            {moneyWasted.toLocaleString("en-IN", {
              style: "currency",
              currency: "INR",
              maximumFractionDigits: 2,
            })}
          </strong>
          <span>Money recorded as wasted</span>
        </div>
      </div>

      <form className="tracker-form" onSubmit={addRecord}>
        <label htmlFor="wasteCategory">What was wasted?</label>

        <select
          id="wasteCategory"
          value={category}
          onChange={(event) => setCategory(event.target.value)}
        >
          {CATEGORIES.map((item) => (
            <option key={item} value={item}>
              {item}
            </option>
          ))}
        </select>

        <label htmlFor="wasteDescription">
          Describe what happened
        </label>

        <input
          id="wasteDescription"
          type="text"
          placeholder="e.g. Bought food that went uneaten"
          value={description}
          onChange={(event) => setDescription(event.target.value)}
          maxLength={500}
          required
        />

        <label htmlFor="wasteAmount">
          Amount wasted (₹ for money; optional otherwise)
        </label>

        <input
          id="wasteAmount"
          type="number"
          min="0"
          max="1000000000"
          step="0.01"
          placeholder="e.g. 150"
          value={amount}
          onChange={(event) => setAmount(event.target.value)}
        />

        <label htmlFor="wasteLesson">
          How will you reduce this waste?
        </label>

        <textarea
          id="wasteLesson"
          rows="3"
          placeholder="e.g. Plan meals before shopping"
          value={lesson}
          onChange={(event) => setLesson(event.target.value)}
          maxLength={1000}
          required
        />

        <button type="submit" disabled={saving}>
          {saving ? "Saving..." : "+ Record Waste"}
        </button>
      </form>

      {message && (
        <p role="status" aria-live="polite">
          {message}
        </p>
      )}

      <div className="practice-history">
        <h3>Your Waste Patterns</h3>

        {Object.keys(categoryCounts).length > 0 && (
          <div className="waste-category-counts">
            {Object.entries(categoryCounts).map(([name, count]) => (
              <span key={name} className="waste-count-chip">
                {name}: {count}
              </span>
            ))}
          </div>
        )}

        {loading ? (
          <p className="empty-state">Loading waste records...</p>
        ) : records.length === 0 ? (
          <p className="empty-state">
            No records yet. When waste happens, use it as a chance to learn.
          </p>
        ) : (
          records.map((record) => (
            <article className="practice-entry" key={record.id}>
              <div className="practice-entry-top">
                <div>
                  <h4>
                    {record.category}: {record.description}
                  </h4>

                  <span>
                    {record.date}
                    {record.amount !== null &&
                      " · Amount: " + record.amount}
                    {record.category === "Money" &&
                      record.amount !== null &&
                      " INR"}
                  </span>
                </div>

                <button
                  type="button"
                  className="delete-button"
                  onClick={() => deleteRecord(record.id)}
                >
                  Delete
                </button>
              </div>

              <p>
                <strong>Next time:</strong> {record.lesson}
              </p>
            </article>
          ))
        )}
      </div>
    </section>
  );
}

export default MottainaiTracker;

