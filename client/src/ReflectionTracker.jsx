
import { useEffect, useState } from "react";
import API_BASE_URL from "./config/api.js";
const API_URL = `${API_BASE_URL}/api/reflections`;

// Return today's date in the computer's local timezone.
function getToday() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");

  return `${year}-${month}-${day}`;
}

function ReflectionTracker() {
  // State stores the user's three reflection answers.
  const [win, setWin] = useState("");
  const [challenge, setChallenge] = useState("");
  const [improvement, setImprovement] = useState("");

  // Store reflection history loaded from the database.
  const [entries, setEntries] = useState([]);

  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [saved, setSaved] = useState(false);
  const [message, setMessage] = useState("");

  // Load previous reflections from the API when the component mounts.
  useEffect(() => {
    let active = true;

    async function loadReflections() {
      try {
        const response = await fetch(API_URL);
        const result = await response.json();

        if (!response.ok || !result.success) {
          throw new Error(
            result.message || "Could not load reflections."
          );
        }

        if (active) {
          // Convert database field names to the UI's date property.
          const loadedEntries = result.data.map((entry) => ({
            ...entry,
            date: entry.reflection_date,
          }));

          setEntries(loadedEntries);
        }
      } catch (error) {
        if (active) {
          setMessage(
            error.message || "Could not connect to the Reflection API."
          );
        }
      } finally {
        if (active) {
          setLoading(false);
        }
      }
    }

    loadReflections();

    // Avoid updating state after unmounting.
    return () => {
      active = false;
    };
  }, []);

  // Save a new reflection to the SQLite database.
  async function handleSave(event) {
    event.preventDefault();

    if (
      !win.trim() ||
      !challenge.trim() ||
      !improvement.trim()
    ) {
      setMessage("Please answer all three reflection questions.");
      return;
    }

    setSaving(true);
    setSaved(false);
    setMessage("");

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          win: win.trim(),
          challenge: challenge.trim(),
          improvement: improvement.trim(),
          reflection_date: getToday(),
        }),
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(
          result.message || "Could not save the reflection."
        );
      }

      // Use the ID generated by SQLite.
      const newEntry = {
        ...result.data,
        date: result.data.reflection_date,
      };

      // Add the new entry to the beginning of the history.
      setEntries((previousEntries) => [
        newEntry,
        ...previousEntries,
      ]);

      // Clear the form after a successful save.
      setWin("");
      setChallenge("");
      setImprovement("");
      setSaved(true);
      setMessage("Reflection saved successfully!");
    } catch (error) {
      setMessage(
        error.message || "Could not save the reflection."
      );
    } finally {
      setSaving(false);
    }
  }

  // Delete a reflection from the database.
  async function deleteReflection(id) {
    if (!window.confirm("Delete this reflection?")) {
      return;
    }

    setMessage("");
    setSaved(false);

    try {
      const response = await fetch(`${API_URL}/${id}`, {
        method: "DELETE",
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(
          result.message || "Could not delete the reflection."
        );
      }

      setEntries((previousEntries) =>
        previousEntries.filter((entry) => entry.id !== id)
      );

      setMessage("Reflection deleted successfully.");
    } catch (error) {
      setMessage(
        error.message || "Could not delete the reflection."
      );
    }
  }

  // Display database dates in a readable format.
  function formatDate(date) {
    if (!date) return "";

    const parsedDate = new Date(`${date.slice(0, 10)}T00:00:00`);

    if (Number.isNaN(parsedDate.getTime())) {
      return date;
    }

    return parsedDate.toLocaleDateString("en-IN", {
      day: "numeric",
      month: "short",
      year: "numeric",
    });
  }

  return (
    <section className="reflection-tracker">
      <p className="eyebrow">HANSEI · REFLECT AND LEARN</p>

      <h2>Daily Reflection</h2>

      <p className="reflection-description">
        Every experience can teach you something.
      </p>

      <form className="reflection-form" onSubmit={handleSave}>
        <label htmlFor="reflection-win">
          1. What went well today?
        </label>

        <textarea
          id="reflection-win"
          value={win}
          onChange={(event) => {
            setWin(event.target.value);
            setSaved(false);
          }}
          placeholder="Celebrate a small win..."
          maxLength={2000}
          required
        />

        <label htmlFor="reflection-challenge">
          2. What was challenging?
        </label>

        <textarea
          id="reflection-challenge"
          value={challenge}
          onChange={(event) => {
            setChallenge(event.target.value);
            setSaved(false);
          }}
          placeholder="What would you handle differently?"
          maxLength={2000}
          required
        />

        <label htmlFor="reflection-improvement">
          3. What is one improvement for tomorrow?
        </label>

        <textarea
          id="reflection-improvement"
          value={improvement}
          onChange={(event) => {
            setImprovement(event.target.value);
            setSaved(false);
          }}
          placeholder="Choose one small, practical action..."
          maxLength={2000}
          required
        />

        <button type="submit" disabled={saving}>
          {saving ? "Saving..." : "Save Reflection"}
        </button>

        {saved && (
          <p className="success" role="status">
            Reflection saved successfully!
          </p>
        )}

        {message && !saved && (
          <p role="status" aria-live="polite">
            {message}
          </p>
        )}
      </form>

      <div className="reflection-history">
        <h3>Previous Reflections</h3>

        {loading ? (
          <p className="empty-expenses">
            Loading reflections...
          </p>
        ) : entries.length === 0 ? (
          <p className="empty-expenses">
            Your reflection history will appear here.
          </p>
        ) : (
          entries.map((entry) => (
            <article className="reflection-entry" key={entry.id}>
              <div className="reflection-entry-header">
                <p className="reflection-date">
                  {formatDate(entry.date)}
                </p>

                <button
                  type="button"
                  className="delete-button"
                  onClick={() => deleteReflection(entry.id)}
                >
                  Delete
                </button>
              </div>

              <h4>What went well</h4>
              <p>{entry.win}</p>

              <h4>Challenge</h4>
              <p>{entry.challenge}</p>

              <h4>Tomorrow's improvement</h4>
              <p>{entry.improvement}</p>
            </article>
          ))
        )}
      </div>
    </section>
  );
}

export default ReflectionTracker;

