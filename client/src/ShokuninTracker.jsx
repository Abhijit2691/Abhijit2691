
import { useEffect, useState } from "react";
import API_BASE_URL from "./config/api.js";
const API_URL = `${API_BASE_URL}/api/shokunin`;

// Return today's date in the computer's local timezone.
function getToday() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");

  return `${year}-${month}-${day}`;
}

function ShokuninTracker() {
  // Store practice records and form values in React state.
  const [skills, setSkills] = useState([]);
  const [skillName, setSkillName] = useState("");
  const [minutes, setMinutes] = useState("");
  const [learning, setLearning] = useState("");

  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [message, setMessage] = useState("");

  // Load practice records from the database when the component mounts.
  useEffect(() => {
    let active = true;

    async function loadSkills() {
      try {
        const response = await fetch(API_URL);
        const result = await response.json();

        if (!response.ok || !result.success) {
          throw new Error(
            result.message || "Could not load practice records."
          );
        }

        if (active) {
          // Match database fields to the existing UI property names.
          const loadedSkills = result.data.map((record) => ({
            ...record,
            skillName: record.skill,
            minutes: Number(record.minutes),
            date: record.practice_date,
          }));

          setSkills(loadedSkills);
        }
      } catch (error) {
        if (active) {
          setMessage(
            error.message || "Could not connect to the Shokunin API."
          );
        }
      } finally {
        if (active) {
          setLoading(false);
        }
      }
    }

    loadSkills();

    // Prevent state updates after the component unmounts.
    return () => {
      active = false;
    };
  }, []);

  // Save a practice session to SQLite through the backend API.
  async function addPractice(event) {
    event.preventDefault();

    const numericMinutes = Number(minutes);

    if (
      !skillName.trim() ||
      !Number.isInteger(numericMinutes) ||
      numericMinutes <= 0 ||
      numericMinutes > 1440 ||
      !learning.trim()
    ) {
      setMessage(
        "Enter a skill, valid practice minutes (1–1440), and learning notes."
      );
      return;
    }

    setSaving(true);
    setMessage("");

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          skill: skillName.trim(),
          minutes: numericMinutes,
          learning: learning.trim(),
          practice_date: getToday(),
        }),
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(
          result.message || "Could not save the practice session."
        );
      }

      // Use the ID generated by SQLite.
      const newPractice = {
        ...result.data,
        skillName: result.data.skill,
        minutes: Number(result.data.minutes),
        date: result.data.practice_date,
      };

      // Add the new session to the beginning of the history.
      setSkills((previousSkills) => [
        newPractice,
        ...previousSkills,
      ]);

      // Reset the form after a successful save.
      setSkillName("");
      setMinutes("");
      setLearning("");
      setMessage("Practice session saved successfully.");
    } catch (error) {
      setMessage(
        error.message || "Could not save the practice session."
      );
    } finally {
      setSaving(false);
    }
  }

  // Delete a practice session from the database.
  async function deletePractice(id) {
    if (!window.confirm("Delete this practice record?")) {
      return;
    }

    setMessage("");

    try {
      const response = await fetch(`${API_URL}/${id}`, {
        method: "DELETE",
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(
          result.message || "Could not delete the practice record."
        );
      }

      setSkills((previousSkills) =>
        previousSkills.filter((skill) => skill.id !== id)
      );

      setMessage("Practice record deleted successfully.");
    } catch (error) {
      setMessage(
        error.message || "Could not delete the practice record."
      );
    }
  }

  // Calculate total practice time across all sessions.
  const totalMinutes = skills.reduce(
    (total, skill) => total + skill.minutes,
    0
  );

  return (
    <section className="tracker-card shokunin-tracker">
      <div className="tracker-heading">
        <div>
          <p className="principle-label">JAPANESE PRINCIPLE</p>
          <h2>🛠️ Shokunin — Skill Mastery</h2>
          <p>Small practice sessions build long-term mastery.</p>
        </div>
      </div>

      <div className="shokunin-summary">
        <div>
          <strong>{skills.length}</strong>
          <span>Practice sessions</span>
        </div>

        <div>
          <strong>
            {Math.floor(totalMinutes / 60)}h {totalMinutes % 60}m
          </strong>
          <span>Total practice time</span>
        </div>
      </div>

      <form onSubmit={addPractice} className="tracker-form">
        <label htmlFor="skillName">Skill you are practising</label>

        <input
          id="skillName"
          type="text"
          placeholder="e.g. React, SQL, piano"
          value={skillName}
          onChange={(event) => setSkillName(event.target.value)}
          maxLength={200}
          required
        />

        <label htmlFor="practiceMinutes">
          Practice time (minutes)
        </label>

        <input
          id="practiceMinutes"
          type="number"
          min="1"
          max="1440"
          step="1"
          placeholder="e.g. 30"
          value={minutes}
          onChange={(event) => setMinutes(event.target.value)}
          required
        />

        <label htmlFor="learning">What did you learn today?</label>

        <textarea
          id="learning"
          placeholder="Write one thing you learned or improved..."
          value={learning}
          onChange={(event) => setLearning(event.target.value)}
          maxLength={2000}
          rows="3"
          required
        />

        <button type="submit" disabled={saving}>
          {saving ? "Saving..." : "+ Save Practice"}
        </button>
      </form>

      {message && (
        <p role="status" aria-live="polite">
          {message}
        </p>
      )}

      <div className="practice-history">
        <h3>Your Practice History</h3>

        {loading ? (
          <p className="empty-state">
            Loading practice records...
          </p>
        ) : skills.length === 0 ? (
          <p className="empty-state">
            Your journey starts with one practice session. Add your first entry!
          </p>
        ) : (
          skills.map((skill) => (
            <article className="practice-entry" key={skill.id}>
              <div className="practice-entry-top">
                <div>
                  <h4>{skill.skillName}</h4>
                  <span>
                    {skill.date} · {skill.minutes} minutes
                  </span>
                </div>

                <button
                  type="button"
                  className="delete-button"
                  onClick={() => deletePractice(skill.id)}
                  aria-label={`Delete practice record for ${skill.skillName}`}
                >
                  Delete
                </button>
              </div>

              <p>{skill.learning}</p>
            </article>
          ))
        )}
      </div>
    </section>
  );
}

export default ShokuninTracker;

